export function isAnswered(q: Question, value: unknown): boolean {
  if (q.type === 'intro' || q.type === 'surprise') return true
  if (value === null || value === undefined || value === '') return false
  if (Array.isArray(value)) return value.length > 0
  return true
}

export function countableQuestions(list: Question[] = QUESTIONS): Question[] {
  return list.filter((q) => q.type !== 'intro' && q.type !== 'surprise')
}

